class CommandFailedError(subprocess.CalledProcessError):
    """CalledProcessError whose str() appends the captured output tail, so the
    failure's own message is visible in the pytest traceback under any
    --show-capture setting (plain prints can be hidden by --show-capture=no)."""

    def __str__(self):
        msg = super().__str__()
        if self.output:
            text = self.output if isinstance(self.output, str) else self.output.decode("utf-8", errors="replace")
            msg += "\n----- last lines of command output -----\n" + text
        return msg


class CommandTimeoutError(subprocess.TimeoutExpired):
    """TimeoutExpired whose str() appends the captured output tail and the
    stuck process's state dump."""

    def __str__(self):
        msg = super().__str__()
        if self.output:
            text = self.output if isinstance(self.output, str) else self.output.decode("utf-8", errors="replace")
            msg += "\n----- last lines of command output -----\n" + text
        if self.stderr:
            text = self.stderr if isinstance(self.stderr, str) else self.stderr.decode("utf-8", errors="replace")
            msg += "\n----- stuck process state -----\n" + text
        return msg


def _collect_stuck_process_diagnostics(proc):
    """Best-effort state dump of a timed-out process and its children, returned
    as text (pure /proc reads: ptrace/gdb is blocked by yama scope for
    non-ancestors)."""

    import glob

    lines = []

    def dump_status(pid):
        try:
            with open(f"/proc/{pid}/cmdline") as f:
                lines.append(f"pid {pid}: {f.read().replace(chr(0), ' ').strip()}")
            with open(f"/proc/{pid}/status") as f:
                lines.extend("  " + l.strip() for l in f if l.startswith(("State:", "Threads:", "VmRSS:")))
            for task in glob.glob(f"/proc/{pid}/task/*"):
                tid = task.rsplit("/", 1)[1]
                state, wchan = "?", "?"
                try:
                    with open(f"{task}/stat") as f:
                        state = f.read().rsplit(")", 1)[1].split()[0]
                except Exception:
                    pass
                try:
                    with open(f"{task}/wchan") as f:
                        wchan = f.read().strip()
                except Exception:
                    pass
                lines.append(f"  tid {tid}: state={state} wchan={wchan}")
        except Exception:
            pass

    pids = {proc.pid}
    try:
        for stat_path in glob.glob("/proc/[0-9]*/stat"):
            with open(stat_path) as f:
                fields = f.read().rsplit(")", 1)[1].split()
            if int(fields[1]) == proc.pid:  # ppid -> direct children
                pids.add(int(stat_path.split("/")[2]))
    except Exception:
        pass
    for pid in sorted(pids):
        dump_status(pid)
    return "\n".join(lines)


def _kill_group(proc, reap_timeout=10):
    """SIGKILL proc's process group and reap proc. A process stuck in the kernel
    (e.g. in the NPU driver) dies only when it leaves it: don't block on it,
    subprocess reaps it later."""
    try:
        os.killpg(proc.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    try:
        proc.wait(timeout=reap_timeout)
    except subprocess.TimeoutExpired:
        pass


def _run_with_group_kill(*popenargs, timeout=None, error_tail_lines=None, **kwargs):
    """Like subprocess.check_call, but kills the process group on timeout or interrupt so
    helpers spawned by the tool (e.g. the qemu CSS simulator) do not outlive it.

    With error_tail_lines, the command's stdout/stderr is captured to a temp
    file; on timeout or non-zero exit the raised exception's message includes
    the last lines (and, on timeout, the stuck process's state), so a CI
    failure shows its own cause in the traceback under any capture setting."""

    import tempfile

    output_file = None
    if error_tail_lines is not None:
        output_file = tempfile.NamedTemporaryFile(mode="w+b", prefix="torq-cmd-", delete=False)
        kwargs["stdout"] = output_file
        kwargs["stderr"] = subprocess.STDOUT

    proc = None
    # Set once the process group is gone; any other exit (Ctrl+C, SIGTERM,
    # pytest-timeout, ...) kills the group in the finally block.
    done = False
    try:
        proc = subprocess.Popen(*popenargs, start_new_session=True, **kwargs)
        # The tool runs in its own session, so it never gets the SIGINT:
        # don't let Popen.wait() wait 0.25 s for it to exit on Ctrl+C.
        proc._sigint_wait_secs = 0
        failure = None
        try:
            retcode = proc.wait(timeout=timeout)
            done = True
            if retcode:
                failure = CommandFailedError(retcode, popenargs[0])
        except subprocess.TimeoutExpired:
            diagnostics = _collect_stuck_process_diagnostics(proc)
            _kill_group(proc)
            done = True
            failure = CommandTimeoutError(popenargs[0], timeout, stderr=diagnostics)

        if failure is not None and output_file is not None:
            try:
                output_file.flush()
                with open(output_file.name, "rb") as f:
                    lines = f.read().decode("utf-8", errors="replace").splitlines()
                failure.output = "\n".join(lines[-error_tail_lines:])
            except Exception:
                pass
        if failure is not None:
            raise failure
    finally:
        if proc is not None and not done:
            _kill_group(proc)
        if output_file is not None:
            output_file.close()
            try:
                os.unlink(output_file.name)
            except OSError:
                pass


def _find_iree_tool(env_var, tool_name):
    """Find IREE tool binary, checking environment variable first, then BUILD_DIR fallback."""

    # Check environment variable first
    env_path = os.getenv(env_var)
    if env_path:
        return env_path
    
    # Fall back to BUILD_DIR based path
    fallback_paths = [BUILD_DIR / 'third_party/iree/tools' / tool_name,
                      BUILD_DIR / 'runtime/tools' / tool_name,
                      BUILD_DIR / 'compiler/tools' / tool_name]
    for path in fallback_paths:
        if path.exists():
            return str(path)

    # Check if tool is in the path
    tool_path = shutil.which(tool_name)
    if tool_path:
        return tool_path

    raise FileNotFoundError(f"Could not find {tool_name}.")


# libraries of the system are left out of the binary versions, like the Python version
_SYSTEM_LIBRARY_DIRS = ('/lib/', '/lib64/', '/usr/lib/', '/usr/lib64/', '/System/')

# version of each tool path, computed once per process
_binary_versions = {}


def _executed_binary(file_path):
    """
    The binary that running file_path executes: pip installs the tools as Python scripts that
    start the binary of the wheel.
    """
    with open(file_path, 'rb') as f:
        if f.read(2) != b'#!':
            return Path(file_path).resolve()

    name = Path(file_path).name
    if name == 'torq-compile':
        from torq.compiler.tools.binaries import find_tool
        return Path(find_tool(name)).resolve()
    if name == 'torq-run-module':
        from torq._runtime_libs import library_path
        return (Path(library_path) / name).resolve()
    if name == 'iree-benchmark-module':
        from iree._runtime_libs import library_path
        return (Path(library_path) / name).resolve()

    raise ValueError(f"{file_path} is a script that starts an unknown binary")


def _macos_linked_libraries(binary):
    """The libraries that binary loads directly, resolved like the macOS dynamic linker does."""
    load_commands = subprocess.run(['otool', '-l', str(binary)], capture_output=True, text=True, check=True).stdout
    rpaths = [str(binary.parent) + p[len('@loader_path'):] if p.startswith('@loader_path') else
              str(binary.parent) + p[len('@executable_path'):] if p.startswith('@executable_path') else p
              for p in re.findall(r'^\s+path (.*) \(offset \d+\)$', load_commands, re.MULTILINE)]

    install_names = subprocess.run(['otool', '-L', str(binary)], capture_output=True, text=True, check=True).stdout
    libraries = []
    for name in re.findall(r'^\s+(\S.*?) \(compatibility', install_names, re.MULTILINE):
        # the system libraries are in the dyld shared cache, not in files; a library lists its
        # own install name too
        if name.startswith(_SYSTEM_LIBRARY_DIRS) or Path(name).name == binary.name:
            continue
        if name.startswith('@rpath/'):
            candidates = [Path(rpath) / name[len('@rpath/'):] for rpath in rpaths]
        elif name.startswith(('@loader_path/', '@executable_path/')):
            candidates = [binary.parent / name.split('/', 1)[1]]
        else:
            candidates = [Path(name)]
        found = next((c.resolve() for c in candidates if c.exists()), None)
        if found is None:
            raise FileNotFoundError(f"{binary} loads {name}, which was not found")
        if found != binary and not str(found).startswith(_SYSTEM_LIBRARY_DIRS):
            libraries.append(found)
    return libraries


def _linked_libraries(binary):
    """The libraries that binary loads, its dependencies included, without those of the system."""
    if sys.platform == 'darwin':
        libraries, pending = [], [binary]
        while pending:
            for library in _macos_linked_libraries(pending.pop()):
                if library not in libraries:
                    libraries.append(library)
                    pending.append(library)
        return libraries

    # ldd lists the dependencies of the dependencies too
    ldd = subprocess.run(['ldd', str(binary)], capture_output=True, text=True, check=True).stdout
    if 'not found' in ldd:
        raise FileNotFoundError(f"{binary} loads a library that was not found:\n{ldd}")
    return [Path(p).resolve() for p in re.findall(r'=> (\S+) \(0x', ldd)
            if not p.startswith(_SYSTEM_LIBRARY_DIRS)]


def _binary_version(request, prefix, file_path):
    """
    The version of a tool: the hash of the binary it runs and of the libraries that binary loads,
    so that it changes only when the code changes, not when it is rebuilt to the same bytes or
    installed in another place. Falls back to the mtime of file_path if the binary or its
    libraries cannot be found.
    """
    if file_path not in _binary_versions:
        try:
            binary = _executed_binary(file_path)
            files = [binary] + _linked_libraries(binary)
            version = prefix + _hash_data(sorted((f.name, _hash_file(request, f)) for f in files))
        except (OSError, ValueError, ImportError, subprocess.CalledProcessError) as e:
            # a warning, so that pytest lists it in its summary
            warnings.warn(f"versioning {file_path} by its mtime: {e}")
            version = prefix + "mtime_" + str(os.path.getmtime(file_path))
        _binary_versions[file_path] = version
    return _binary_versions[file_path]


